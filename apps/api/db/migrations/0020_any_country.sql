-- The country CHECKs were written inline, so they are found by what they say, not by name.
DO $$
DECLARE
  item record;
BEGIN
  FOR item IN
    SELECT c.conrelid::regclass AS tbl, c.conname
    FROM pg_constraint c
    WHERE c.contype = 'c'
      AND c.conrelid IN ('company'::regclass, 'company_market'::regclass, 'lookup_request'::regclass)
      AND pg_get_constraintdef(c.oid) LIKE '%country%'
      AND pg_get_constraintdef(c.oid) LIKE '%''US-DE''%'
  LOOP
    EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', item.tbl, item.conname);
  END LOOP;
END;
$$;

ALTER TABLE lookup_request
  ADD CONSTRAINT lookup_request_country_fkey FOREIGN KEY (country) REFERENCES jurisdiction (code);

-- "DE" for US-DE as before, and now the state for every US company. Null outside the US.
ALTER TABLE company ALTER COLUMN incorporation_state
  SET EXPRESSION AS (CASE WHEN incorporation_country LIKE 'US-%' THEN substr(incorporation_country, 4) END);
